export function getResolvedLanguage(language?: string | null): AppLanguage {
  const normalized = (language || "").toLowerCase();
  const base = normalized.split("-")[0] as AppLanguage;
  return SUPPORTED_LANGUAGES.has(base) ? base : "en";
}

function detectDeviceLanguage(): AppLanguage {
  try {
    return getResolvedLanguage(Intl.DateTimeFormat().resolvedOptions().locale);
  } catch {
    return "en";
  }
}

export async function loadLanguagePreference(): Promise<AppLanguage> {
  const stored = await SecureStore.getItemAsync(LANGUAGE_STORAGE_KEY);
  const language = stored ? getResolvedLanguage(stored) : detectDeviceLanguage();
  if (i18n.resolvedLanguage !== language) {
    await i18n.changeLanguage(language);
  }
  return language;
}

export async function setLanguagePreference(language: AppLanguage): Promise<void> {
  await SecureStore.setItemAsync(LANGUAGE_STORAGE_KEY, language);
  await i18n.changeLanguage(language);
}

